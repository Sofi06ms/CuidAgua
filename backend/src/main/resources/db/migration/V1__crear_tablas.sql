-- Migración inicial de CuidAgua: tablas de reportes ciudadanos y avisos de suministro.

CREATE TABLE reportes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo            VARCHAR(30)  NOT NULL,
    descripcion     VARCHAR(500) NOT NULL,
    direccion       VARCHAR(255) NOT NULL,
    colonia         VARCHAR(120) NOT NULL,
    latitud         DOUBLE PRECISION,
    longitud        DOUBLE PRECISION,
    foto_url        VARCHAR(500),
    estado          VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE',
    usuario_id      VARCHAR(64)  NOT NULL,
    usuario_nombre  VARCHAR(255) NOT NULL,
    fecha_creacion  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_reportes_tipo
        CHECK (tipo IN ('FUGA', 'TUBERIA_ROTA', 'SIN_AGUA', 'BAJA_PRESION', 'OTRO')),
    CONSTRAINT ck_reportes_estado
        CHECK (estado IN ('PENDIENTE', 'EN_PROCESO', 'RESUELTO', 'RECHAZADO')),
    CONSTRAINT ck_reportes_latitud
        CHECK (latitud IS NULL OR latitud BETWEEN -90 AND 90),
    CONSTRAINT ck_reportes_longitud
        CHECK (longitud IS NULL OR longitud BETWEEN -180 AND 180)
);

CREATE INDEX idx_reportes_colonia ON reportes (LOWER(colonia));
CREATE INDEX idx_reportes_fecha_creacion ON reportes (fecha_creacion DESC);

CREATE TABLE avisos (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                  VARCHAR(120)  NOT NULL,
    mensaje                 VARCHAR(1000) NOT NULL,
    colonia                 VARCHAR(120)  NOT NULL,
    tipo                    VARCHAR(30)   NOT NULL,
    fecha_inicio            TIMESTAMP,
    fecha_restablecimiento  TIMESTAMP     NOT NULL,
    creado_por_id           VARCHAR(64)   NOT NULL,
    creado_por_nombre       VARCHAR(255)  NOT NULL,
    fecha_creacion          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_avisos_tipo
        CHECK (tipo IN ('CORTE', 'RESTABLECIMIENTO', 'MANTENIMIENTO', 'BAJA_PRESION')),
    CONSTRAINT ck_avisos_fechas
        CHECK (fecha_inicio IS NULL OR fecha_inicio < fecha_restablecimiento)
);

CREATE INDEX idx_avisos_colonia ON avisos (LOWER(colonia));
CREATE INDEX idx_avisos_fecha_creacion ON avisos (fecha_creacion DESC);
